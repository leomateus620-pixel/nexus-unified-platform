import type { CruzPart, GroundPoint } from "./scene-types";

export type RoofTrace = {
  item: string;
  shape: CruzPart["roof"];
  boundary: GroundPoint[];
  eave: number;
  rise: number;
  base?: number;
  parapet?: CruzPart["parapet"];
  reverse?: boolean;
};

function trace(item: string, shape: RoofTrace["shape"], start: GroundPoint, end: GroundPoint,
  opposite: GroundPoint, eave: number, rise: number, settings: Partial<RoofTrace> = {}): RoofTrace {
  const far: GroundPoint = [opposite[0] + end[0] - start[0], opposite[1] + end[1] - start[1]];
  return { item, shape, boundary: [start, end, far, opposite], eave, rise, ...settings };
}

